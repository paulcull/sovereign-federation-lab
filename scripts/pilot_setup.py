"""Private synthetic identities with explicit delegation and revocable expiry.

Tokens are opaque test credentials, not a bank IdP. File replacement is atomic;
receivers reload identity policy each request. Certificates require restart to
rotate and are never silently regenerated by this script.
"""
import datetime
import json
import math
import os
from pathlib import Path
import secrets
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / '.pilot'
BASE_ROLES = ['owner', 'api', 'authority', 'peer-sg', 'peer-uk', 'peer-us']
ROLES = BASE_ROLES + ['servicing']
STORES = {'sg': 'STORE-SG-01', 'uk': 'STORE-GB-01', 'us': 'STORE-US-01'}
COUNTRIES = {'sg': 'SG', 'uk': 'GB', 'us': 'US'}
COMMAND_GRANTS = {'update_contact': ['contact_info.value'],
                  'withdraw_consent': ['consent.status'], 'restore_consent': ['consent.status']}
PROFILES = {
    'crm-sg': dict(entity_id='LE-SG-01', processing_country='SG', actions=['system', 'read', 'command'], source_system='crm-sg'),
    'sg-owner': dict(entity_id='LE-SG-01', processing_country='SG', actions=['read', 'command']),
    'uk-servicing': dict(entity_id='LE-GB-02', processing_country='GB', actions=['read', 'command']),
    'uk-contact-only': dict(entity_id='LE-GB-02', processing_country='GB', actions=['read', 'command']),
    'uk-business': dict(entity_id='LE-GB-03', processing_country='GB', actions=['read']),
    'us-reader': dict(entity_id='LE-US-01', processing_country='US', actions=['read']),
    'uk-from-us': dict(entity_id='LE-GB-02', processing_country='US', actions=['read', 'command']),
    'case-mdm-reader-sg': dict(entity_id='LE-SG-01', processing_country='SG', actions=['read']),
    'case-mdm-reader-uk': dict(entity_id='LE-GB-02', processing_country='GB', actions=['read']),
}


def write(path, value):
    temporary = path.with_name(path.name + '.new')
    fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, 'w') as stream:
        stream.write(json.dumps(value, indent=2) + '\n')
    temporary.chmod(0o600)
    temporary.replace(path)


def read(role):
    return json.loads((OUT / role / 'config.json').read_text())


def openssl(*args):
    subprocess.run(['openssl', *args], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def certificate_expiry(role):
    result = subprocess.run(['openssl', 'x509', '-in', str(OUT / role / 'tls.crt'), '-enddate', '-noout'],
                            check=True, capture_output=True, text=True)
    timestamp = datetime.datetime.strptime(result.stdout.strip().split('=', 1)[1], '%b %d %H:%M:%S %Y %Z')
    return timestamp.replace(tzinfo=datetime.timezone.utc).timestamp()


def lifecycle(expiry):
    if expiry <= time.time():
        raise SystemExit('Pilot certificate expired; explicit certificate renewal and service restart required')
    return dict(not_before=int(time.time()) - 60, expires_at=int(expiry), revoked=False)


def certificate(role):
    directory = OUT / role
    directory.mkdir(mode=0o700)
    hostname = 'pilot-' + role
    ca = OUT / 'issuer'
    openssl('req', '-newkey', 'rsa:2048', '-nodes', '-keyout', str(directory / 'tls.key'),
            '-out', str(directory / 'tls.csr'), '-subj', '/CN=' + hostname)
    extension = directory / 'tls.ext'
    extension.write_text('subjectAltName=DNS:' + hostname + '\nextendedKeyUsage=serverAuth,clientAuth\n')
    openssl('x509', '-req', '-in', str(directory / 'tls.csr'), '-CA', str(ca / 'ca.crt'),
            '-CAkey', str(ca / 'ca.key'), '-CAcreateserial', '-out', str(directory / 'tls.crt'),
            '-days', '14', '-extfile', str(extension))
    (directory / 'ca.crt').write_bytes((ca / 'ca.crt').read_bytes())
    (directory / 'tls.csr').unlink()
    extension.unlink()


def base_config(role):
    region = role.removeprefix('peer-')
    return dict(version=2, mode='synthetic', role='peer' if role.startswith('peer-') else role,
                deployment=dict(processing_countries=[COUNTRIES.get(region, 'SG')]))


def setup():
    os.umask(0o077)
    existing = (OUT / 'ready.json').exists()
    if existing:
        ready = json.loads((OUT / 'ready.json').read_text())
        if ready.get('version') not in (1, 2) or not all((OUT / r / 'config.json').exists() for r in BASE_ROLES):
            raise SystemExit('Pilot identity directory incomplete or unknown; recover explicitly')
        configs = {r: read(r) for r in BASE_ROLES}
        if any(c.get('version') not in (1, 2) for c in configs.values()):
            raise SystemExit('Unknown pilot identity layout; recover explicitly')
        if set(configs['owner'].get('principals', {})) - set(PROFILES) or set(configs['api'].get('principals', {})) - set(PROFILES):
            raise SystemExit('Unknown registered identity; explicit configuration migration required')
        expected_identities = {'api', 'peer-sg', 'peer-uk', 'peer-us'}
        if set(configs['owner'].get('identities', {})) != expected_identities:
            raise SystemExit('Unknown workload identity layout; explicit configuration migration required')
        for role in BASE_ROLES:
            if configs[role].get('role') != ('peer' if role.startswith('peer-') else role):
                raise SystemExit('Unexpected pilot role; explicit configuration migration required')
        for identity in list(configs['owner']['identities'].values()) + list(configs['api']['principals'].values()):
            if not isinstance(identity.get('token'), str) or len(identity['token']) < 32:
                raise SystemExit('Invalid legacy credential; explicit recovery required')
        if not (OUT / 'servicing').exists():
            certificate('servicing')
        if (OUT / 'servicing/config.json').exists():
            configs['servicing'] = read('servicing')
    else:
        if OUT.exists() and any(OUT.iterdir()):
            raise SystemExit('Partial pilot setup; move aside the incomplete private directory before retrying')
        OUT.mkdir(exist_ok=True, mode=0o700)
        ca = OUT / 'issuer'
        ca.mkdir(mode=0o700)
        openssl('req', '-x509', '-newkey', 'rsa:2048', '-nodes', '-keyout', str(ca / 'ca.key'),
                '-out', str(ca / 'ca.crt'), '-days', '30', '-subj', '/CN=Sovereign Synthetic Pilot CA')
        for role in ROLES:
            certificate(role)
        configs = {r: {} for r in ROLES}
    expiry = min(certificate_expiry(r) for r in ROLES)
    fresh = lifecycle(expiry)
    for role in ROLES:
        old = configs.setdefault(role, {})
        # An existing v2 deployment registration is never silently overwritten.
        configs[role] = {**base_config(role), **old, 'version': 2}
    owner, api = configs['owner'], configs['api']
    owner.setdefault('principals', {})
    api.setdefault('principals', {})
    for name, profile in PROFILES.items():
        grants = COMMAND_GRANTS if 'command' in profile['actions'] else {}
        if name == 'uk-contact-only':
            grants = {'update_contact': COMMAND_GRANTS['update_contact']}
        default = {**profile, 'id': name, 'command_grants': grants, **fresh}
        owner['principals'][name] = {**default, **owner['principals'].get(name, {})}
        api['principals'][name] = {**default, 'token': secrets.token_urlsafe(32), **api['principals'].get(name, {})}
    identities = owner.setdefault('identities', {})
    api_token = identities.get('api', {}).get('token', secrets.token_urlsafe(32))
    identities['api'] = {**fresh, 'token': api_token, 'role': 'api', **identities.get('api', {})}
    api.update(authority_url='https://pilot-authority:8443', authority_token=api_token)
    peers = owner.setdefault('peers', {})
    for region, store in STORES.items():
        role = 'peer-' + region
        peer = configs[role]
        caller = identities.get(role, {}).get('token', secrets.token_urlsafe(32))
        importer = peer.get('import_token', secrets.token_urlsafe(32))
        identities[role] = {**fresh, 'token': caller, 'role': 'peer', 'store_id': store, **identities.get(role, {})}
        peers[store] = dict(url='https://pilot-' + role + ':8443', import_token=importer)
        peer.update(store_id=store, authority_url='https://pilot-authority:8443', authority_token=caller,
                    import_token=importer, import_credential={**fresh, 'token': importer, **peer.get('import_credential', {})})
    service = configs['servicing']
    service.setdefault('principals', {})
    for name, actions in [('case-owner', ['case.create', 'case.read', 'case.close', 'case.reopen', 'case.export']),
                          ('case-reader', ['case.read'])]:
        service['principals'][name] = {**fresh, 'id': name, 'entity_id': 'LE-SG-01', 'processing_country': 'SG',
            'actions': actions, 'command_grants': {}, 'token': secrets.token_urlsafe(32), **service['principals'].get(name, {})}
    service.update(mdm_url='https://pilot-api:8443', mdm_token=api['principals']['case-mdm-reader-sg']['token'],
                   mdm_export_token=api['principals']['case-mdm-reader-uk']['token'])
    export = service.setdefault('export_identities', {})
    export['peer-uk'] = {**fresh, 'role': 'peer', 'store_id': STORES['uk'], 'token': secrets.token_urlsafe(32), **export.get('peer-uk', {})}
    configs['peer-uk'].update(servicing_url='https://pilot-servicing:8443', servicing_token=export['peer-uk']['token'])
    servicing_principals = configs['peer-uk'].setdefault('servicing_principals', {})
    for name, entity, country in [('case-uk-reader', 'LE-GB-02', 'GB'), ('case-us-reader', 'LE-US-01', 'US')]:
        servicing_principals[name] = {**fresh, 'id': name, 'entity_id': entity, 'processing_country': country,
            'actions': ['case.refresh', 'case.read'], 'command_grants': {}, 'token': secrets.token_urlsafe(32),
            **servicing_principals.get(name, {})}
    for role, config in configs.items():
        credentials = [identity for group in ('principals', 'identities', 'export_identities', 'servicing_principals')
                       for identity in config.get(group, {}).values()]
        if 'import_credential' in config:
            credentials.append(config['import_credential'])
        for credential in credentials:
            end, start = credential.get('expires_at'), credential.get('not_before')
            if (type(end) not in (int, float) or type(start) not in (int, float)
                    or not math.isfinite(end) or not math.isfinite(start)
                    or type(credential.get('revoked')) is not bool):
                raise SystemExit('Invalid existing credential lifecycle; explicit recovery required')
            credential['expires_at'] = min(end, expiry)
        write(OUT / role / 'config.json', config)
    write(OUT / 'ready.json', dict(version=2))
    print('Private synthetic identity configuration ready; existing credentials/certificates preserved; no credentials logged.')


def change_identity(name, rotate=False, workload=False):
    """Rotate/revoke at the accepting authority first; transient requests fail closed."""
    owner, api = read('owner'), read('api')
    expiry = min(certificate_expiry(r) for r in ROLES)
    state = lifecycle(expiry) if rotate else {'revoked': True}
    token = secrets.token_urlsafe(32) if rotate else None
    updates = []
    if workload:
        if name == 'case-export-uk':
            service = read('servicing')
            service['export_identities']['peer-uk'].update(state)
            if rotate:
                service['export_identities']['peer-uk']['token'] = token
            updates.append(('servicing', service))
            if rotate:
                peer = read('peer-uk')
                peer['servicing_token'] = token
                updates.append(('peer-uk', peer))
        elif name in owner['identities']:
            owner['identities'][name].update(state)
            if rotate:
                owner['identities'][name]['token'] = token
            updates.append(('owner', owner))
            if rotate:
                caller = read(name)
                caller['authority_token'] = token
                updates.append((name, caller))
        elif name.startswith('import-peer-') and name.removeprefix('import-') in ROLES:
            role = name.removeprefix('import-')
            peer = read(role)
            peer['import_credential'].update(state)
            if rotate:
                peer['import_token'] = token
                peer['import_credential']['token'] = token
                owner['peers'][peer['store_id']]['import_token'] = token
            updates.append((role, peer))
            if rotate:
                updates.append(('owner', owner))
        else:
            raise SystemExit('Unknown workload identity')
    elif name in api['principals']:
        owner['principals'][name].update(state)
        api['principals'][name].update(state)
        if rotate:
            api['principals'][name]['token'] = token
        updates = [('owner', owner), ('api', api)]
        if rotate and name in ('case-mdm-reader-sg', 'case-mdm-reader-uk'):
            service = read('servicing')
            service['mdm_token' if name.endswith('-sg') else 'mdm_export_token'] = token
            updates.append(('servicing', service))
    else:
        service = read('servicing')
        role, key = 'servicing', 'principals'
        if name not in service[key]:
            service, role, key = read('peer-uk'), 'peer-uk', 'servicing_principals'
        if name not in service.get(key, {}):
            raise SystemExit('Unknown pilot identity')
        service[key][name].update(state)
        if rotate:
            service[key][name]['token'] = token
        updates.append((role, service))
    for role, config in updates:
        write(OUT / role / 'config.json', config)
    print('Synthetic credential rotated.' if rotate else 'Synthetic credential revoked.')


def main(args):
    if not args:
        setup()
        return
    if len(args) != 2 or args[0] not in ('token', 'revoke', 'rotate', 'revoke-workload', 'rotate-workload'):
        raise SystemExit('Usage: pilot_setup.py [token|revoke|rotate|revoke-workload|rotate-workload IDENTITY]')
    command, name = args
    if command == 'token':
        identity = (read('api')['principals'].get(name) or read('servicing')['principals'].get(name)
                    or read('peer-uk').get('servicing_principals', {}).get(name))
        if identity is None or identity.get('revoked') or not identity.get('not_before', float('inf')) <= time.time() < identity.get('expires_at', 0):
            raise SystemExit('Identity unavailable, revoked or expired; explicit rotation required')
        print(identity['token'])  # Only this explicit operator command prints one secret.
    else:
        change_identity(name, rotate=command.startswith('rotate'), workload=command.endswith('-workload'))


if __name__ == '__main__':
    main(sys.argv[1:])
